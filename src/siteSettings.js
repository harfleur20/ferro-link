export function mergeSiteSettings(value) {
  if (!value || typeof value !== "object" || Array.isArray(value)) return defaultSiteSettings;
  return {
    ...Object.fromEntries(
    Object.entries(defaultSiteSettings).map(([section, defaults]) => [
      section,
      value[section] && typeof value[section] === "object" && !Array.isArray(value[section])
        ? { ...defaults, ...value[section] }
        : defaults,
    ]),
    ),
    home: {
      ...defaultSiteSettings.home,
      ...(value.home && typeof value.home === "object" && !Array.isArray(value.home) ? value.home : {}),
      expertiseAreas: Array.isArray(value.home?.expertiseAreas) ? value.home.expertiseAreas : defaultSiteSettings.home.expertiseAreas,
      metiers: Array.isArray(value.home?.metiers) ? value.home.metiers : defaultSiteSettings.home.metiers,
      partners: Array.isArray(value.home?.partners) ? value.home.partners : defaultSiteSettings.home.partners,
    },
    about: {
      ...defaultSiteSettings.about,
      ...(value.about && typeof value.about === "object" && !Array.isArray(value.about) ? value.about : {}),
      gallery: Array.isArray(value.about?.gallery) ? value.about.gallery : defaultSiteSettings.about.gallery,
      values: Array.isArray(value.about?.values) ? value.about.values : defaultSiteSettings.about.values,
    },
    footer: {
      ...defaultSiteSettings.footer,
      ...(value.footer && typeof value.footer === "object" && !Array.isArray(value.footer) ? value.footer : {}),
      phones: Array.isArray(value.footer?.phones) ? value.footer.phones : defaultSiteSettings.footer.phones,
      socials: Array.isArray(value.footer?.socials) ? value.footer.socials : defaultSiteSettings.footer.socials,
    },
    contact: {
      ...defaultSiteSettings.contact,
      ...(value.contact && typeof value.contact === "object" && !Array.isArray(value.contact) ? value.contact : {}),
      phones: Array.isArray(value.contact?.phones) ? value.contact.phones : defaultSiteSettings.contact.phones,
      phoneLinks: Array.isArray(value.contact?.phoneLinks) ? value.contact.phoneLinks : defaultSiteSettings.contact.phoneLinks,
      emails: Array.isArray(value.contact?.emails) ? value.contact.emails : defaultSiteSettings.contact.emails,
      addressLines: Array.isArray(value.contact?.addressLines) ? value.contact.addressLines : defaultSiteSettings.contact.addressLines,
    },
  };
}

export function resolveSiteAssetUrl(source, apiBase) {
  return source.startsWith("/api/site-assets/") ? `${apiBase}${source}` : source;
}

export function getSiteThemeStyle(theme, home = defaultSiteSettings.home) {
  return {
    "--navy": theme.primaryColor,
    "--navy-deep": theme.primaryColor,
    "--lime": theme.accentColor,
    "--lime-bright": theme.accentColor,
    "--body-font": `"${theme.bodyFont}", sans-serif`,
    "--heading-font": `"${theme.headingFont}", sans-serif`,
    "--body-font-size": `${theme.bodySize}px`,
    "--heading-size": `${theme.headingSize}px`,
    "--home-band-image": `url("${home.homeBandImage}")`,
  };
}
